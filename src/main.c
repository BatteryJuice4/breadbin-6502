// ---- settings --------------------------------------------------------------

static void save_settings(void) {
    if (!app.settings_dirty || !app.settings_path[0]) {
        return;
    }
    if (app.settings_corrupt) {
        char bak[SETTINGS_PATH_MAX + 8];
        snprintf(bak, sizeof(bak), "%s.bad", app.settings_path);
        platform_replace_file(app.settings_path, bak);
        fprintf(stderr, "breadbin-6502: kept the unreadable settings file as %s\n", bak);
        app.settings_corrupt = false;
    }
    char err[512];
    if (settings_save_file(&app.settings, app.settings_path, err, sizeof(err))) {
        app.settings_dirty = false;
    } else {
        fprintf(stderr, "breadbin-6502: %s\n", err);
    }
}

static void load_settings(void) {
    app.settings = app.defaults;
    const char* id = app.gp.present ? app.gp.pack.id : BB_GENERIC_ID;
    if (app.cli_settings) {
        snprintf(app.settings_path, sizeof(app.settings_path), "%s", app.cli_settings);
    } else if (!platform_settings_path(id, app.settings_path, sizeof(app.settings_path))) {
        fprintf(stderr, "breadbin-6502: no config directory; settings won't be saved\n");
        app.settings_path[0] = 0;
        return;
    }
    bool missing = false;
    char err[512], warns[2048];
    if (!settings_load_file(&app.settings, app.settings_path, &missing, err, sizeof(err), warns, sizeof(warns))) {
        if (!missing) {
            fprintf(stderr, "breadbin-6502: settings ignored, %s\n", err);
            app.settings_corrupt = true;
        }
    }
    if (warns[0]) {
        fprintf(stderr, "breadbin-6502: settings warnings:\n%s", warns);
    }
}

// ---- mods ------------------------------------------------------------------

static const char* game_id(void) {
    return app.gp.present ? app.gp.pack.id : BB_GENERIC_ID;
}

// The palette from settings; a palette mod that isn't usable falls back to the default.
static void apply_palette(void) {
    const char* id = app.settings.video.palette;
    const palette_t* p = palette_find_builtin(id);
    if (p) {
        video_set_palette(p->rgb);
        return;
    }
    if (!strncmp(id, "mod:", 4)) {
        const int i = modset_find(&app.mods, id + 4);
        if (i >= 0 && app.mods.entries[i]->usable && app.mods.entries[i]->mod.type == MOD_TYPE_PALETTE) {
            video_set_palette(app.mods.entries[i]->mod.palette);
            return;
        }
    }
    video_set_palette(palette_find_builtin(PALETTE_DEFAULT)->rgb);
}

// Enabled mods (load order) -> settings.
static void save_mod_order(void) {
    settings_t* s = &app.settings;
    s->mods_enabled_count = 0;
    for (int i = 0; i < app.mods.order_count && i < SETTINGS_MAX_MODS; i++) {
        const mod_entry_t* e = app.mods.entries[app.mods.order[i]];
        snprintf(s->mods_enabled[s->mods_enabled_count++], SETTINGS_MOD_ID_MAX, "%s", e->file_id);
    }
    app.settings_dirty = true;
}

// Re-check every mod against the loaded game; notice when patch mods need a reload.
static void evaluate_mods(void) {
    modset_evaluate(&app.mods, app.ui.cart_loaded ? app.ui.rom_sha1 : "");
    char sig[sizeof(app.patch_sig)];
    modset_patch_signature(&app.mods, sig, sizeof(sig));
    app.ui.mods_restart_needed = app.ui.cart_loaded && strcmp(sig, app.patch_sig) != 0;
    apply_palette();
    app.cheats_first = true;    // newly enabled "once" cheats apply on the next frame
}

static void scan_mods(void) {
    modset_scan(&app.mods, app.mods_dir, app.mods_bundled);
    evaluate_mods();
}

static void init_mods(void) {
    modset_init(&app.mods, game_id(), BB_VERSION);
    if (!platform_mods_dir(game_id(), app.mods_dir, sizeof(app.mods_dir))) app.mods_dir[0] = 0;
    app.mods_bundled[0] = 0;
    if (app.gp.present && strcmp(app.gp.source, "built in") != 0) {
        const int n = snprintf(app.mods_bundled, sizeof(app.mods_bundled), "%.1000s%cmods", app.gp.source, platform_path_sep());
        if (n < 0 || (size_t)n >= sizeof(app.mods_bundled)) app.mods_bundled[0] = 0;
    }
    modset_scan(&app.mods, app.mods_dir, app.mods_bundled);
    modset_set_enabled(&app.mods, (const char (*)[MOD_ID_MAX])app.settings.mods_enabled, app.settings.mods_enabled_count);
    modset_evaluate(&app.mods, "");
    for (int i = 0; i < app.mods.order_count; i++) {
        const mod_entry_t* e = app.mods.entries[app.mods.order[i]];
        fprintf(stderr, "breadbin-6502: mod \"%s\" enabled%s%s\n", e->file_id, e->status[0] ? ": " : "", e->status);
    }
}

// Patch mods for a game about to start (data = the bytes its sha1 covers; NULL = can't be patched).
static void patch_game(const char* sha1, uint8_t* data, size_t size, const char* why_not) {
    modset_clear_failures(&app.mods);
    modset_evaluate(&app.mods, sha1);
    if (modset_has_patches(&app.mods)) {
        if (data) {
            const int n = modset_apply_patches(&app.mods, data, size);
            fprintf(stderr, "breadbin-6502: %d patch mod%s applied\n", n, n == 1 ? "" : "s");
        } else {
            modset_fail_patches(&app.mods, why_not);
        }
    }
    for (int i = 0; i < app.mods.order_count; i++) {
        const mod_entry_t* e = app.mods.entries[app.mods.order[i]];
        if (e->failed) fprintf(stderr, "breadbin-6502: mod \"%s\": %s\n", e->file_id, e->status);
    }
    modset_patch_signature(&app.mods, app.patch_sig, sizeof(app.patch_sig));
    app.ui.mods_restart_needed = false;
    apply_palette();    // palette mods may be tied to a dump too
}

static void install_mod(const char* path) {
    ui_state_t* u = &app.ui;
    if (!app.mods_dir[0]) {
        snprintf(u->mods_message, sizeof(u->mods_message), "There's no config folder to install mods into.");
        u->mods_message_is_error = true;
        return;
    }
    u->mods_message_is_error = !modset_install(app.mods_dir, path, game_id(), u->mods_message, sizeof(u->mods_message));
    fprintf(stderr, "breadbin-6502: %s\n", u->mods_message);
    if (!u->mods_message_is_error) scan_mods();
}

static void select_mod_file(void) {
    char home[SETTINGS_PATH_MAX] = "";
    platform_home_dir(home, sizeof(home));
    char path[SETTINGS_PATH_MAX], err[256];
    switch (platform_open_mod_dialog(home[0] ? home : NULL, path, sizeof(path), err, sizeof(err))) {
        case FILEDIALOG_OK: install_mod(path); break;
        case FILEDIALOG_CANCEL: break;
        case FILEDIALOG_ERROR: ui_open_mod_browser(home[0] ? home : NULL); break;
    }
    app.accum = 0.0;
}

// ---- diagnostic replays ----------------------------------------------------

static void replay_msg(bool is_error, const char* text) {
    snprintf(app.ui.replay_message, sizeof(app.ui.replay_message), "%s", text);
    app.ui.replay_message_is_error = is_error;
    fprintf(stderr, "breadbin-6502: %s\n", text);
}

static void stop_recording(const char* why) {
    if (!app.recording) return;
    app.recording = false;
    app.ui.replay_recording = false;
    char dir[SETTINGS_PATH_MAX], path[SETTINGS_PATH_MAX + 64], err[512], msg[SETTINGS_PATH_MAX + 256];
    if (app.rec.count == 0) {
        replay_free(&app.rec);
        return;
    }
    if (app.cli_record) {
        snprintf(path, sizeof(path), "%s", app.cli_record);
        app.cli_record = NULL;      // only the first recording goes there
    } else if (!platform_replays_dir(game_id(), dir, sizeof(dir))) {
        replay_msg(true, "The replay wasn't saved: there's no config folder.");
        replay_free(&app.rec);
        return;
    } else {
        // wall-clock time only names the file; it never reaches the emulation
        const time_t now = time(NULL);
        const struct tm* tm = localtime(&now);
        char stamp[32] = "replay";
        if (tm) strftime(stamp, sizeof(stamp), "%Y%m%d-%H%M%S", tm);
        snprintf(path, sizeof(path), "%s%creplay-%s.bbreplay", dir, platform_path_sep(), stamp);
    }
    if (replay_save(&app.rec, path, err, sizeof(err))) {
        snprintf(msg, sizeof(msg), "%sReplay saved (%u frames): %s", why ? why : "", app.rec.count, path);
        replay_msg(false, msg);
    } else {
        snprintf(msg, sizeof(msg), "The replay wasn't saved: %s", err);
        replay_msg(true, msg);
    }
    replay_free(&app.rec);
}

static void finish_playback(void) {
    if (!app.playing) return;
    app.playing = false;
    app.ui.replay_playing = false;
    char msg[256];
    const replay_player_t* p = &app.player;
    if (p->diverged) {
        snprintf(msg, sizeof(msg), "The replay went differently from frame %u on (of %u). Something changed since it was recorded.",
                 p->diverged_at, app.play.count);
    } else if (p->pos < app.play.count) {
        snprintf(msg, sizeof(msg), "Replay stopped at frame %u of %u; all frames so far matched.", p->pos, app.play.count);
    } else {
        snprintf(msg, sizeof(msg), "Replay finished: all %u frames matched.", app.play.count);
    }
    replay_msg(p->diverged, msg);
}

// Something that a replay can't contain happened (reset, other game, mods...).
static void interrupt_replay(const char* what) {
    if (app.recording) {
        char why[128];
        snprintf(why, sizeof(why), "Recording stopped (%s). ", what);
        stop_recording(why);
    }
    finish_playback();
}

static bool use_drive(void);
static bool fast_load_on(void);

static void start_recording(void) {
    replay_header_t h = { 0 };
    snprintf(h.launcher_version, sizeof(h.launcher_version), "%s", BB_VERSION);
    snprintf(h.game_id, sizeof(h.game_id), "%s", game_id());
    snprintf(h.rom_name, sizeof(h.rom_name), "%s", app.ui.rom_name);
    snprintf(h.rom_sha1, sizeof(h.rom_sha1), "%s", app.ui.rom_sha1);
    snprintf(h.media, sizeof(h.media), "%s", app.media.fmt != MEDIA_FMT_UNKNOWN ? media_format_name(app.media.fmt) + 1 : "cartridge");
    h.ntsc = core_frame_rate(app.core) > 55.0;
    sha1_hex(app.roms.kernal, sizeof(app.roms.kernal), h.sysrom_sha1[0]);
    sha1_hex(app.roms.basic, sizeof(app.roms.basic), h.sysrom_sha1[1]);
    sha1_hex(app.roms.chargen, sizeof(app.roms.chargen), h.sysrom_sha1[2]);
    snprintf(h.drive_sha1, sizeof(h.drive_sha1), "%s", core_has_drive(app.core) ? app.roms.drive1541_sha1 : "");
    h.fast_load = use_drive() && fast_load_on();
    for (int i = 0; i < app.mods.order_count && h.mod_count < REPLAY_MAX_MODS; i++) {
        const mod_entry_t* e = app.mods.entries[app.mods.order[i]];
        if (e->usable) snprintf(h.mods[h.mod_count++], sizeof(h.mods[0]), "%s@%s", e->mod.id, e->sha1);
    }
    replay_init(&app.rec, &h);
    app.recording = true;
    app.ui.replay_recording = true;
    app.ui.replay_frame = 0;
    app.ui.replay_message[0] = 0;
    fprintf(stderr, "breadbin-6502: recording a replay\n");
}

// --replay: use the replay's video standard and mods (this session only).
static bool prepare_playback(void) {
    char err[512];
    if (!replay_load(app.cli_replay, &app.play, err, sizeof(err))) {
        fprintf(stderr, "breadbin-6502: %s: %s\n", app.cli_replay, err);
        snprintf(app.ui.replay_message, sizeof(app.ui.replay_message), "Can't play the replay: %s", err);
        app.ui.replay_message_is_error = true;
        return false;
    }
    const replay_header_t* h = &app.play.header;
    fprintf(stderr, "breadbin-6502: replay of \"%s\" (%s, %u frames, launcher %s)\n",
            h->rom_name, h->ntsc ? "NTSC" : "PAL", app.play.count, h->launcher_version);
    if (!app.cli_video_std) app.cli_video_std = h->ntsc ? 2 : 1;
    return true;
}

// Enable exactly the replay's mods; note any that are missing or different.
static void use_replay_mods(void) {
    const replay_header_t* h = &app.play.header;
    char ids[REPLAY_MAX_MODS][MOD_ID_MAX];
    char notes[1024] = "";
    for (int i = 0; i < h->mod_count; i++) {
        char id[MOD_ID_MAX] = "";
        const char* at = strchr(h->mods[i], '@');
        const int len = at ? (int)(at - h->mods[i]) : (int)strlen(h->mods[i]);
        snprintf(id, sizeof(id), "%.*s", len < MOD_ID_MAX ? len : MOD_ID_MAX - 1, h->mods[i]);
        snprintf(ids[i], MOD_ID_MAX, "%s", id);
        const int k = modset_find(&app.mods, id);
        const size_t nl = strlen(notes);
        if (k < 0) snprintf(notes + nl, sizeof(notes) - nl, " Mod \"%s\" isn't installed.", id);
        else if (at && strcmp(app.mods.entries[k]->sha1, at + 1) != 0) snprintf(notes + nl, sizeof(notes) - nl, " Mod \"%s\" is a different version.", id);
    }
    modset_set_enabled(&app.mods, (const char (*)[MOD_ID_MAX])ids, h->mod_count);
    if (notes[0]) {
        char msg[1200];
        snprintf(msg, sizeof(msg), "The replay may not match:%s", notes);
        replay_msg(true, msg);
    }
}

static void check_replay_environment(void) {
    const replay_header_t* h = &app.play.header;
    char s[3][41];
    sha1_hex(app.roms.kernal, sizeof(app.roms.kernal), s[0]);
    sha1_hex(app.roms.basic, sizeof(app.roms.basic), s[1]);
    sha1_hex(app.roms.chargen, sizeof(app.roms.chargen), s[2]);
    if (strcmp(s[0], h->sysrom_sha1[0]) || strcmp(s[1], h->sysrom_sha1[1]) || strcmp(s[2], h->sysrom_sha1[2])) {
        fprintf(stderr, "breadbin-6502: warning: the replay was recorded with different system ROMs\n");
    }
    const char* drive = use_drive() ? app.roms.drive1541_sha1 : "";
    if (strcmp(drive, h->drive_sha1) != 0) {
        fprintf(stderr, "breadbin-6502: warning: the replay was recorded %s\n", !h->drive_sha1[0] ? "without the 1541 drive"
                : !drive[0] ? "with the 1541 drive, but no 1541 ROM is installed" : "with a different 1541 ROM");
    }
    if (strcmp(h->launcher_version, BB_VERSION) != 0) {
        fprintf(stderr, "breadbin-6502: note: the replay was recorded with launcher %s (this is %s)\n", h->launcher_version, BB_VERSION);
    }
}

// The game is loaded: start feeding the replay (false if it's a different game).
static bool start_playback(void) {
    const replay_header_t* h = &app.play.header;
    char msg[512];
    if (!app.ui.cart_loaded) {
        snprintf(msg, sizeof(msg), "Load \"%s\" to play this replay (pass the game file after --replay FILE).", h->rom_name);
        replay_msg(true, msg);
        return false;
    }
    if (strcmp(app.ui.rom_sha1, h->rom_sha1) != 0) {
        snprintf(msg, sizeof(msg), "This replay is for \"%s\" (SHA-1 %s), not the loaded game.", h->rom_name, h->rom_sha1);
        replay_msg(true, msg);
        return false;
    }
    replay_player_init(&app.player, &app.play);
    app.playing = true;
    app.ui.replay_playing = true;
    app.ui.replay_total = app.play.count;
    return true;
}

static void set_message(bool is_error, const char* fmt, const char* arg) {
    snprintf(app.ui.message, sizeof(app.ui.message), fmt, arg);
    app.ui.message_is_error = is_error;
}

static void enter_game(void) {
    app.ui.screen = UI_SCREEN_NONE;
    app.ui.capture_action = UI_CAPTURE_NONE;
    app.accum = 0.0;
    input_release_all();
}

static void set_title(const char* rom_name) {
    if (app.gp.present) snprintf(app.title, sizeof(app.title), "%s", app.gp.pack.title);
    else if (rom_name && rom_name[0]) snprintf(app.title, sizeof(app.title), "Breadbin-6502 - %s", rom_name);
    else snprintf(app.title, sizeof(app.title), "Breadbin-6502");
    update_title();
}

static cart_mode_t pack_cart_mode(gamepack_cart_t t) {
    switch (t) {
        case GAMEPACK_CART_8K: return CART_MODE_8K;
        case GAMEPACK_CART_16K: return CART_MODE_16K;
        case GAMEPACK_CART_ULTIMAX: return CART_MODE_ULTIMAX;
        default: return (cart_mode_t)0;
    }
}

static const char* kind_noun(media_kind_t k) {
    return k == MEDIA_KIND_DISK ? "disk" : k == MEDIA_KIND_TAPE ? "tape" : "cartridge";
}

// The game pack's media kind must match the file's (a disk image can't be a cartridge game).
static bool check_kind(media_kind_t k, char* why, size_t why_size) {
    const gamepack_t* p = &app.gp.pack;
    const media_kind_t want = p->media == GAMEPACK_MEDIA_DISK ? MEDIA_KIND_DISK :
                              p->media == GAMEPACK_MEDIA_TAPE ? MEDIA_KIND_TAPE : MEDIA_KIND_CARTRIDGE;
    if (k == want) return true;
    snprintf(why, why_size, "This is a %s image, but %s is a %s game. It's probably a different game.",
             kind_noun(k), p->title, kind_noun(want));
    return false;
}

static rom_status_t check_hash(const char* sha1, char* why, size_t why_size) {
    const gamepack_t* p = &app.gp.pack;
    if (p->known_sha1_count == 0) return ROM_STATUS_UNVERIFIED;
    if (gamepack_knows_sha1(p, sha1)) return ROM_STATUS_KNOWN;
    snprintf(why, why_size, "This doesn't look like a known copy of %s (SHA-1 %s). "
             "It may be a different version or a bad dump, and mods may not work.", p->title, sha1);
    return ROM_STATUS_UNKNOWN;
}

static rom_status_t check_media(const media_image_t* img, char* why, size_t why_size) {
    why[0] = 0;
    if (!app.gp.present) return ROM_STATUS_GENERIC;
    if (!check_kind(media_format_kind(img->fmt), why, why_size)) return ROM_STATUS_UNKNOWN;
    return check_hash(img->sha1, why, why_size);
}

// Check a cartridge against the game pack; why explains an UNKNOWN result.
static rom_status_t check_cart(const cart_t* c, char* why, size_t why_size) {
    why[0] = 0;
    if (!app.gp.present) return ROM_STATUS_GENERIC;
    if (!check_kind(MEDIA_KIND_CARTRIDGE, why, why_size)) return ROM_STATUS_UNKNOWN;
    const gamepack_t* p = &app.gp.pack;
    const cart_mode_t want = pack_cart_mode(p->cart_type);
    if (want && c->mode != want) {
        snprintf(why, why_size, "This is a %s cartridge, but %s is a %s cartridge. It's probably a different game.",
                 cart_mode_name(c->mode), p->title, cart_mode_name(want));
        return ROM_STATUS_UNKNOWN;
    }
    return check_hash(c->sha1, why, why_size);
}

// The emulated 1541 is used when its ROM is installed, unless the game pack or
// --no-drive says otherwise.
static bool use_drive(void) {
    if (!app.roms.has_1541 || app.cli_no_drive) return false;
    return !(app.gp.present && app.gp.pack.drive == GAMEPACK_DRIVE_NONE);
}

// Save copies are kept for normal play only: a replay must start from the
// original disk every time, so recording and playback leave them alone.
static bool disk_saves_on(void) {
    return app.disks_dir[0] && !app.recording && !app.playing && !app.fresh_media &&
           !app.cli_record && !app.cli_replay && !app.cli_headless;
}

// Write the disk's save copy if the drive changed it.
static void flush_disk(void) {
    core_disk_t* disk = media_disk(&app.media);
    if (!disk || !disk->dirty) return;
    disk->dirty = false;
    if (!app.disk_save_path[0] || !disk_saves_on()) return;
    char err[1200];
    if (disksave_write(app.disk_save_path, disk, err, sizeof(err))) {
        fprintf(stderr, "breadbin-6502: the game wrote to its disk; saved a copy in %s\n", app.disk_save_path);
    } else {
        fprintf(stderr, "breadbin-6502: %s\n", err);
        set_message(true, "The game wrote to its disk, but the copy couldn't be saved: %s", err);
    }
}

// Instant KERNAL LOADs alongside the drive: the player's setting, unless the game
// pack needs every load to go through the real drive; a replay uses what it recorded.
static bool fast_load_on(void) {
    if (app.cli_replay) return app.play.header.fast_load;
    if (app.gp.present && app.gp.pack.drive == GAMEPACK_DRIVE_1541) return false;
    return app.settings.disk.fast_load;
}

// Put the opened disk (if any) into the drive, using its save copy if there is one.
static void attach_disk(void) {
    app.media.use_drive = core_has_drive(app.core);
    app.media.fast_load = app.media.use_drive && fast_load_on();
    app.ui.drive_present = app.media.use_drive && media_disk(&app.media) != NULL;
    app.ui.drive_pack_forced = app.gp.present && app.gp.pack.drive == GAMEPACK_DRIVE_1541;
    app.disk_save_path[0] = 0;
    core_disk_t* disk = media_disk(&app.media);
    if (!disk || !app.media.use_drive) {
        core_insert_disk(app.core, NULL);
        return;
    }
    if (disk_saves_on() && disksave_path(app.disks_dir, app.media.sha1, app.disk_save_path, sizeof(app.disk_save_path))) {
        gcr_image_t copy;
        char err[1200];
        if (disksave_read(app.disk_save_path, &copy, err, sizeof(err))) {
            media_set_surface(&app.media, &copy);
            fprintf(stderr, "breadbin-6502: using the saved copy of this disk: %s\n", app.disk_save_path);
        } else if (err[0]) {
            fprintf(stderr, "breadbin-6502: ignoring the disk's save copy: %s\n", err);
        }
    }
    core_insert_disk(app.core, media_disk(&app.media));
}

// Take out any disk/tape (the machine keeps running until the caller resets it).
static void eject_media(void) {
    flush_disk();
    core_insert_disk(app.core, NULL);
    app.disk_save_path[0] = 0;
    core_set_file_loader(app.core, NULL, NULL);
    core_remove_tape(app.core);
    media_close(&app.media);
    app.booting = false;
    app.ui.loading = false;
    app.ui.can_swap = false;
    app.ui.drive_present = false;
}

// Reset the machine and autostart the inserted disk/tape (warp until loaded).
static void boot_media(void) {
    if (app.media.fmt == MEDIA_FMT_TAP) {
        core_insert_tape(app.core, app.media.tap_v1, app.media.tap_v1_size);     // rewind
    }
    core_reset(app.core);
    const gamepack_t* p = &app.gp.pack;
    const autostart_opts_t opts = {
        .file = app.gp.present ? p->load_file : NULL,
        .done_pc = app.gp.present ? p->load_done_pc : -1,
        .done_frames = app.gp.present ? (uint32_t)p->load_done_frames : 0,
    };
    autostart_begin(&app.boot, app.core, app.media.fmt, &opts);
    app.booting = true;
    app.ui.loading = true;
    app.ui.loading_seconds = 0.0f;
}

static void file_base_name(const char* path, char* out, size_t out_size) {
    const char* base = path;
    for (const char* p = path; *p; p++) if (*p == '/' || *p == '\\') base = p + 1;
    // Strip the extension before truncating, or a dot inside the name ("v1.06") would be taken for it.
    const char* dot = strrchr(base, '.');
    const int len = (dot && dot != base) ? (int)(dot - base) : (int)strlen(base);
    snprintf(out, out_size, "%.*s", len, base);
}

static void remember_rom(const char* path) {
    if (strcmp(app.settings.rom_path, path) != 0) {
        snprintf(app.settings.rom_path, sizeof(app.settings.rom_path), "%s", path);
        app.settings_dirty = true;
        save_settings();
    }
}

// --coverage: merge the core's map into <dir>/<sha1>.bbcov and start over (for
// the next game, or because the session ends).
static void coverage_flush(void) {
    const uint32_t* map = app.core ? core_coverage(app.core) : NULL;
    if (!app.cli_coverage || !map || !app.coverage_sha1[0]) return;
    char path[1100], err[1300];
    if (!coverage_path(app.cli_coverage, app.coverage_sha1, path, sizeof(path))) {
        fprintf(stderr, "breadbin-6502: coverage: bad folder or game SHA-1\n");
    } else if (coverage_merge_save(path, app.coverage_sha1, map, err, sizeof(err))) {
        fprintf(stderr, "breadbin-6502: coverage: %u addresses ran as code this session; merged into %s\n",
                coverage_count(map), path);
    } else {
        fprintf(stderr, "breadbin-6502: coverage: %s\n", err);
    }
    core_coverage_clear(app.core);
}

// A game was loaded: trace its code from here on (with --coverage).
static void coverage_begin(const char* sha1) {
    if (!app.cli_coverage) return;
    coverage_flush();
    if (!core_coverage_enable(app.core, true)) {
        fprintf(stderr, "breadbin-6502: coverage: out of memory\n");
        return;
    }
    core_coverage_clear(app.core);
    snprintf(app.coverage_sha1, sizeof(app.coverage_sha1), "%s", sha1);
}

// Recompiled code (docs/recomp.md): on when the build has it, the settings (or --core)
// want it and it matches the inserted cartridge. Frames are identical either way, so
// it can change at any time, also during replays.
static bool recomp_wanted(void) {
    return app.cli_core ? app.cli_core == 1 : app.settings.emulation.recompiled;
}

static void recomp_apply(bool report) {
    ui_state_t* u = &app.ui;
#ifdef BB_HAS_RECOMP
    u->recomp_built = true;
    char why[256] = "";
    const bool was = core_recomp_active(app.core);
    if (!recomp_wanted()) {
        core_set_recomp(app.core, NULL, NULL, 0);
        snprintf(u->recomp_status, sizeof(u->recomp_status), "Off: the interpreter runs the game.");
    } else if (core_recomp_active(app.core) || core_set_recomp(app.core, bb_rc_get_program(), why, sizeof(why))) {
        snprintf(u->recomp_status, sizeof(u->recomp_status),
                 "On: the game's code runs as C generated from your ROM by %s. Same frames as the interpreter.",
                 bb_rc_get_program()->generator);
    } else {
        snprintf(u->recomp_status, sizeof(u->recomp_status), "Not used: %s. The interpreter runs the game.", why);
    }
    u->recomp_active = core_recomp_active(app.core);
    if (report && (recomp_wanted() || was)) {
        fprintf(stderr, "breadbin-6502: recompiled code: %s\n", u->recomp_status);
    }
#else
    (void)u;
    if (report && app.cli_core == 1) {
        fprintf(stderr, "breadbin-6502: --core recomp: this build has no recompiled code; running the interpreter\n");
    }
#endif
}

// Share of the CPU's cycles the recompiled code ran (since the last reset).
static void recomp_stats(void) {
    if (!app.core || !app.ui.recomp_built || !recomp_wanted()) return;
    const uint64_t total = core_cycle_count(app.core);
    if (total) {
        fprintf(stderr, "breadbin-6502: recompiled code ran %.1f%% of %llu cycles\n",
                100.0 * (double)core_recomp_cycles(app.core) / (double)total, (unsigned long long)total);
    }
}

static void insert_cart(const cart_t* cart, const char* path, rom_status_t status, bool remember) {
    interrupt_replay("another game was loaded");
    eject_media();
    core_insert_cart(app.core, cart);
    recomp_apply(true);
    ui_state_t* u = &app.ui;
    u->cart_loaded = true;
    u->media_kind = "Cartridge";
    snprintf(u->rom_path, sizeof(u->rom_path), "%s", path);
    if (cart->name[0]) {
        snprintf(u->rom_name, sizeof(u->rom_name), "%s", cart->name);
    } else {
        // many .crt files have an empty name: use the file name without extension
        file_base_name(path, u->rom_name, sizeof(u->rom_name));
    }
    snprintf(u->rom_sha1, sizeof(u->rom_sha1), "%s", cart->sha1);
    u->rom_mode = cart_mode_name(cart->mode);
    u->rom_status = status;
    u->message[0] = 0;
    fprintf(stderr, "breadbin-6502: cartridge \"%s\" (%s, sha1 %s)\n",
            u->rom_name, cart_mode_name(cart->mode), cart->sha1);
    if (cart->header_fixed) {
        fprintf(stderr, "breadbin-6502: note: the .crt header says 16K, but there's only ROM at $8000: running it as 8K\n");
    }
    set_title(u->rom_name);
    if (remember) remember_rom(path);
    app.cheats_first = true;
    coverage_begin(cart->sha1);
    enter_game();
}

static void insert_media(media_image_t* img, const char* path, rom_status_t status, bool remember) {
    interrupt_replay("another game was loaded");
    eject_media();
    if (core_has_cart(app.core)) core_remove_cart(app.core);
    app.media = *img;                   // takes over the image's buffers
    memset(img, 0, sizeof(*img));
    core_set_file_loader(app.core, media_serve, &app.media);
    attach_disk();
    ui_state_t* u = &app.ui;
    const media_kind_t kind = media_format_kind(app.media.fmt);
    static char mode[48];
    snprintf(mode, sizeof(mode), "%s image (%s)", kind_noun(kind), media_format_name(app.media.fmt));
    u->cart_loaded = true;
    u->media_kind = kind == MEDIA_KIND_TAPE ? "Tape" : "Disk";
    u->can_swap = app.media.fmt != MEDIA_FMT_PRG;
    snprintf(u->rom_path, sizeof(u->rom_path), "%s", path);
    file_base_name(path, u->rom_name, sizeof(u->rom_name));
    snprintf(u->rom_sha1, sizeof(u->rom_sha1), "%s", app.media.sha1);
    u->rom_mode = mode;
    u->rom_status = status;
    u->message[0] = 0;
    fprintf(stderr, "breadbin-6502: %s \"%s\" (sha1 %s)\n", mode, u->rom_name, app.media.sha1);
    set_title(u->rom_name);
    if (remember) remember_rom(path);
    coverage_begin(app.media.sha1);
    boot_media();
    enter_game();
}

static bool load_cart(const char* path, load_mode_t mode);

// Any supported file: cartridge, disk or tape (detected by content, then extension).
static bool load_rom(const char* path, load_mode_t mode) {
    if (app.ui.blocked[0]) return false;
    uint8_t* data = NULL;
    size_t size = 0;
    char err[256];
    if (!rom_read_file(path, TAP_MAX_SIZE, &data, &size, err, sizeof(err))) {
        set_message(true, "%s", err);
        fprintf(stderr, "breadbin-6502: %s\n", err);
        return false;
    }
    const media_format_t fmt = media_detect(path, data, size);
    if (fmt == MEDIA_FMT_CRT || fmt == MEDIA_FMT_BIN) {
        free(data);
        return load_cart(path, mode);
    }
    if (fmt == MEDIA_FMT_UNKNOWN) {
        free(data);
        set_message(true, "%s isn't a C64 cartridge (.crt .bin), disk (.d64 .g64 .prg) or tape (.tap .t64) image.", path);
        return false;
    }
    media_image_t img;
    if (!media_open(&img, fmt, data, size, err, sizeof(err))) {   // frees data on failure
        set_message(true, "%s", err);
        fprintf(stderr, "breadbin-6502: %s: %s\n", path, err);
        return false;
    }
    char why[512];
    const rom_status_t status = check_media(&img, why, sizeof(why));
    if (status == ROM_STATUS_UNKNOWN) {
        fprintf(stderr, "breadbin-6502: warning: %s\n", why);
        if (mode == LOAD_INTERACTIVE) {
            snprintf(app.pending_path, sizeof(app.pending_path), "%s", path);
            snprintf(app.ui.confirm_text, sizeof(app.ui.confirm_text), "%s", why);
            app.ui.confirm_open = true;
            media_close(&img);
            return false;
        }
    }
    if (img.fmt == MEDIA_FMT_D64) {
        patch_game(img.sha1, img.data, d64_data_size(&img.d64), NULL);
        if (app.patch_sig[0] && !media_rebuild_surface(&img, err, sizeof(err))) {
            fprintf(stderr, "breadbin-6502: %s\n", err);
        }
    } else if (img.fmt == MEDIA_FMT_PRG) {
        patch_game(img.sha1, img.data, img.size, NULL);
    } else if (img.fmt == MEDIA_FMT_G64) {
        patch_game(img.sha1, NULL, 0, "patch mods can't change .g64 disk images");
    } else {
        patch_game(img.sha1, NULL, 0, "patch mods can't change tape images (.tap, .t64)");
    }
    insert_media(&img, path, status, mode == LOAD_INTERACTIVE || mode == LOAD_CONFIRMED);
    return true;
}

// "Swap disk/tape": put another image of the same kind in, without a reset.
static void swap_media(const char* path) {
    uint8_t* data = NULL;
    size_t size = 0;
    char err[256];
    if (!rom_read_file(path, TAP_MAX_SIZE, &data, &size, err, sizeof(err))) {
        set_message(true, "%s", err);
        return;
    }
    const media_format_t fmt = media_detect(path, data, size);
    const bool same_kind = fmt != MEDIA_FMT_UNKNOWN && fmt != MEDIA_FMT_CRT && fmt != MEDIA_FMT_BIN &&
                           media_format_kind(fmt) == media_format_kind(app.media.fmt);
    if (!same_kind) {
        free(data);
        set_message(true, "That isn't a %s image.", kind_noun(media_format_kind(app.media.fmt)));
        return;
    }
    media_image_t img;
    if (!media_open(&img, fmt, data, size, err, sizeof(err))) {
        set_message(true, "%s", err);
        return;
    }
    interrupt_replay("the disk or tape was swapped");
    flush_disk();
    core_insert_disk(app.core, NULL);
    media_close(&app.media);
    app.media = img;
    core_set_file_loader(app.core, media_serve, &app.media);
    attach_disk();
    if (fmt == MEDIA_FMT_TAP) {
        core_insert_tape(app.core, app.media.tap_v1, app.media.tap_v1_size);
        core_tape_play(app.core);
    } else {
        core_remove_tape(app.core);
    }
    char name[64];
    file_base_name(path, name, sizeof(name));
    set_message(false, "Inserted %s. Close the menu to continue.", name);
    fprintf(stderr, "breadbin-6502: swapped in %s (sha1 %s)\n", path, app.media.sha1);
}

static bool load_cart(const char* path, load_mode_t mode) {
    static cart_t cart;     // ~16 KB, keep off the stack
    char err[256];
    if (app.ui.blocked[0]) return false;
    const uint16_t load_addr = app.gp.present ? app.gp.pack.bin_load_address : 0;
    if (!rom_load_cart(path, load_addr, &cart, err, sizeof(err))) {
        set_message(true, "%s", err);
        fprintf(stderr, "breadbin-6502: %s\n", err);
        return false;
    }
    char why[512];
    const rom_status_t status = check_cart(&cart, why, sizeof(why));
    if (status == ROM_STATUS_UNKNOWN) {
        fprintf(stderr, "breadbin-6502: warning: %s\n", why);
        if (mode == LOAD_INTERACTIVE) {
            snprintf(app.pending_path, sizeof(app.pending_path), "%s", path);
            snprintf(app.ui.confirm_text, sizeof(app.ui.confirm_text), "%s", why);
            app.ui.confirm_open = true;
            return false;
        }
    }
    {
        static uint8_t data[0x4000 * 4];
        const size_t n = cart_data_size(&cart);
        if (n <= sizeof(data)) {
            cart_data_get(&cart, data);
            patch_game(cart.sha1, data, n, NULL);
            cart_data_put(&cart, data);
        } else {
            patch_game(cart.sha1, NULL, 0, "this cartridge layout can't be patched");
        }
    }
    insert_cart(&cart, path, status, mode == LOAD_INTERACTIVE || mode == LOAD_CONFIRMED);
    return true;
}

static void start_without_cart(void) {
    interrupt_replay("the cartridge was removed");
    eject_media();
    core_remove_cart(app.core);
    app.ui.cart_loaded = false;
    app.ui.rom_status = ROM_STATUS_NONE;
    app.ui.rom_path[0] = app.ui.rom_name[0] = app.ui.rom_sha1[0] = 0;
    app.patch_sig[0] = 0;
    modset_clear_failures(&app.mods);
    evaluate_mods();
    set_title(NULL);
    enter_game();
}

static void select_rom(bool swap) {
    char dir[SETTINGS_PATH_MAX] = { 0 };
    // start in the folder of the current/last ROM
    const char* last = app.ui.rom_path[0] ? app.ui.rom_path : app.settings.rom_path;
    snprintf(dir, sizeof(dir), "%s", last);
    char* sep = strrchr(dir, platform_path_sep());
    if (sep) *sep = 0; else dir[0] = 0;

    char path[SETTINGS_PATH_MAX], err[256];
    switch (platform_open_rom_dialog(dir, path, sizeof(path), err, sizeof(err))) {
        case FILEDIALOG_OK:
            if (swap) swap_media(path); else load_rom(path, LOAD_INTERACTIVE);
            break;
        case FILEDIALOG_CANCEL:
            break;
        case FILEDIALOG_ERROR:
            if (platform_native_dialog_available()) {
                fprintf(stderr, "breadbin-6502: %s; using the built-in browser\n", err);
            }
            app.browser_swap = swap;
            ui_open_file_browser(dir[0] ? dir : NULL);
            break;
    }
    app.accum = 0.0;    // the dialog blocked the frame loop
}


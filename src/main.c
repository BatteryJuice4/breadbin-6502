static bool parse_args(int argc, char* argv[]) {
    for (int i = 1; i < argc; i++) {
        const char* a = argv[i];
        const char* v = (i + 1 < argc) ? argv[i + 1] : NULL;
        if (!strcmp(a, "--sysroms") && v)       { app.sysrom_dir = v; i++; }
        else if (!strcmp(a, "--settings") && v) { app.cli_settings = v; i++; }
        else if (!strcmp(a, "--gamepack") && v) { app.cli_gamepack = v; i++; }
        else if (!strcmp(a, "--generic"))       { app.cli_generic = true; }
        else if (!strcmp(a, "--pal"))           { app.cli_video_std = 1; }
        else if (!strcmp(a, "--ntsc"))          { app.cli_video_std = 2; }
        else if (!strcmp(a, "--scale") && v)    { app.scale_override = atoi(v); i++; }
        else if (!strcmp(a, "--frames") && v)   { app.quit_after_frames = atol(v); i++; }
        else if (!strcmp(a, "--replay") && v)   { app.cli_replay = v; i++; }
        else if (!strcmp(a, "--verify"))        { app.cli_verify = true; }
        else if (!strcmp(a, "--record") && v)   { app.cli_record = v; i++; }
        else if (!strcmp(a, "--headless"))      { app.cli_headless = true; }
        else if (!strcmp(a, "--coverage") && v) { app.cli_coverage = v; i++; }
        else if (!strcmp(a, "--core") && v && (!strcmp(v, "recomp") || !strcmp(v, "interp"))) {
            app.cli_core = !strcmp(v, "recomp") ? 1 : 2;
            i++;
        }
        else if (!strcmp(a, "--no-drive"))      { app.cli_no_drive = true; }
        else if (a[0] != '-' && !app.cli_cart)  { app.cli_cart = a; }
        else { usage(); return false; }
    }
    if (app.scale_override < 0 || app.scale_override > 8) app.scale_override = 0;
    if (app.cli_verify && !app.cli_replay) {
        fprintf(stderr, "breadbin-6502: --verify needs --replay FILE\n");
        return false;
    }
    if (app.cli_headless && (app.quit_after_frames <= 0 || app.cli_replay)) {
        fprintf(stderr, "breadbin-6502: --headless needs --frames N (use --verify to play a replay)\n");
        return false;
    }
    return true;
}

static void load_system_roms(void) {
    char dir[1024] = { 0 };
    const char* rom_dir = app.sysrom_dir;
    if (!rom_dir && platform_system_rom_dir(dir, sizeof(dir))) {
        rom_dir = dir;
    }
    char err[512];
    if (!sysroms_load(&app.roms, rom_dir, err, sizeof(err))) {
        fprintf(stderr, "breadbin-6502: %s\n", err);
    }
    snprintf(app.ui.system_roms, sizeof(app.ui.system_roms), "%s%s%s",
             sysroms_source_name(app.roms.kernal_basic_source),
             app.roms.chargen_source != app.roms.kernal_basic_source ? " (custom CHARGEN)" : "",
             !app.roms.has_1541 ? "" : app.roms.drive1541_name ? " + 1541 drive" : " + 1541 drive (unknown ROM)");
    if (app.roms.has_1541) {
        fprintf(stderr, "breadbin-6502: 1541 ROM %s (%s)\n", app.roms.drive1541_sha1,
                app.roms.drive1541_name ? app.roms.drive1541_name : "not a known dump; using it anyway");
    }
}

static void add_note(const char* text) {
    char* notes = app.ui.pack_notes;
    size_t len = strlen(notes);
    snprintf(notes + len, sizeof(app.ui.pack_notes) - len, "%s%s", len ? "\n" : "", text);
}

// Find the game pack (see gamepack_load) and layer its defaults over the built-in ones.
static void load_game_pack(void) {
    settings_default(&app.defaults);
    const gamepack_embedded_t emb = {
        bb_gamepack_toml, bb_gamepack_toml_size,
        bb_gamepack_icon, bb_gamepack_icon_size,
        bb_gamepack_banner, bb_gamepack_banner_size,
    };
    char err[512], warns[4096];
    if (!gamepack_load(app.cli_gamepack, &emb, !app.cli_generic, &app.gp, &app.defaults,
                       err, sizeof(err), warns, sizeof(warns))) {
        snprintf(app.ui.blocked, sizeof(app.ui.blocked), "The game pack can't be loaded: %s", err);
        settings_default(&app.defaults);
        memset(&app.gp, 0, sizeof(app.gp));
    }
    if (warns[0]) fprintf(stderr, "breadbin-6502: game pack warnings:\n%s", warns);
    if (!app.gp.present) return;
    const gamepack_t* p = &app.gp.pack;
    fprintf(stderr, "breadbin-6502: game pack \"%s\" (%s) from %s\n", p->title, p->id, app.gp.source);
    if (app.gp.icon_png && !image_decode_png(app.gp.icon_png, app.gp.icon_size, BB_ICON_MAX, &app.icon, err, sizeof(err))) {
        fprintf(stderr, "breadbin-6502: icon.png ignored: %s\n", err);
    }
    if (app.gp.banner_png && !image_decode_png(app.gp.banner_png, app.gp.banner_size, BB_BANNER_MAX, &app.banner, err, sizeof(err))) {
        fprintf(stderr, "breadbin-6502: banner.png ignored: %s\n", err);
    }
    if (p->sid_model == 8580) {
        add_note("This game expects the 8580 SID chip. The emulator models the 6581, so the sound may differ.");
    }
}

// Reasons the game can't start at all (shown on the Select-ROM screen).
static void check_playable(void) {
    if (app.ui.blocked[0] || !app.gp.present) return;
    const gamepack_t* p = &app.gp.pack;
    if (!gamepack_launcher_ok(p, BB_VERSION)) {
        snprintf(app.ui.blocked, sizeof(app.ui.blocked),
                 "This game pack needs Breadbin-6502 %s or newer. This is version %s.",
                 p->min_launcher_version, BB_VERSION);
    } else if (p->needs_original_roms && app.roms.kernal_basic_source == SYSROMS_SOURCE_OPENROMS) {
        char dir[1024] = "the --sysroms folder";
        if (!app.sysrom_dir) platform_system_rom_dir(dir, sizeof(dir));
        snprintf(app.ui.blocked, sizeof(app.ui.blocked),
                 "%s needs the original Commodore system ROMs. Put your own dumps named kernal.rom, "
                 "basic.rom and chargen.rom in this folder, then start again:\n%.600s",
                 p->title, app.sysrom_dir ? app.sysrom_dir : dir);
    } else if (p->drive == GAMEPACK_DRIVE_1541 && !app.roms.has_1541) {
        char dir[1024] = "the --sysroms folder";
        if (!app.sysrom_dir) platform_system_rom_dir(dir, sizeof(dir));
        snprintf(app.ui.blocked, sizeof(app.ui.blocked),
                 "%s needs a real 1541 disk drive, which needs its ROM. Put your own dump in this folder, "
                 "named 1541.rom (16 KB) or 1541-c000.rom and 1541-e000.rom (8 KB each), then start again:\n%.600s",
                 p->title, app.sysrom_dir ? app.sysrom_dir : dir);
    }
}

// Sound from the core; silent while a disk/tape loads at warp speed.
static void core_audio(const float* samples, int num_samples, void* user_data) {
    if (!app.booting && !app.cli_verify && !app.cli_headless) audio_push(samples, num_samples, user_data);
}

static core_video_std_t video_std(void) {
    if (app.cli_video_std) return app.cli_video_std == 2 ? CORE_VIDEO_NTSC : CORE_VIDEO_PAL;
    return (app.gp.present && app.gp.pack.ntsc) ? CORE_VIDEO_NTSC : CORE_VIDEO_PAL;
}

void bb_register_plugins(void);     // generated from BB_PLUGIN_SOURCES (cmake/plugins_registry.c.in)

sapp_desc sokol_main(int argc, char* argv[]) {
    bb_register_plugins();
    if (!parse_args(argc, argv)) {
        exit(2);
    }
    load_game_pack();
    load_settings();
    init_mods();
    if (!platform_states_dir(game_id(), app.states_dir, sizeof(app.states_dir))) app.states_dir[0] = 0;
    if (!platform_disks_dir(game_id(), app.disks_dir, sizeof(app.disks_dir))) app.disks_dir[0] = 0;
    const bool replay_ready = app.cli_replay && prepare_playback();
    if (app.cli_verify && !replay_ready) exit(2);
    if (replay_ready) use_replay_mods();
    load_system_roms();
    if (replay_ready) check_replay_environment();
    check_playable();
    if (app.cli_verify || app.cli_headless) {
        // no window, no sound
    } else if (!audio_init(app.settings.audio.latency_ms)) {
        fprintf(stderr, "breadbin-6502: no audio device, running silently\n");
    }
    audio_set_settings(&app.settings.audio);
    app.core = core_create(&(core_desc_t){
        .video_std = video_std(),
        .rom_kernal = app.roms.kernal,   .rom_kernal_size = sizeof(app.roms.kernal),
        .rom_basic = app.roms.basic,     .rom_basic_size = sizeof(app.roms.basic),
        .rom_chargen = app.roms.chargen, .rom_chargen_size = sizeof(app.roms.chargen),
        .rom_1541 = use_drive() ? app.roms.drive1541 : NULL,
        .rom_1541_size = use_drive() ? sizeof(app.roms.drive1541) : 0,
        .audio_sample_rate = audio_sample_rate(),
        .audio_fn = core_audio,
    });
    if (!app.core) {
        fprintf(stderr, "breadbin-6502: failed to create emulator core\n");
        exit(1);
    }
    recomp_apply(app.cli_core == 1);     // matched again whenever a cartridge goes in
    app.frame_period = 1.0 / core_frame_rate(app.core);
    app.scripts = scriptset_create();
    app.plugins = pluginset_create();
    if (!app.scripts || !app.plugins) {
        fprintf(stderr, "breadbin-6502: out of memory\n");
        exit(1);
    }
    input_init(&app.settings.input);
    gamepad_init();

    ui_state_t* u = &app.ui;
    u->settings = &app.settings;
    u->mods = &app.mods;
    u->defaults = &app.defaults;
    u->game_title = app.gp.present ? app.gp.pack.title : "Breadbin-6502";
    u->version = BB_VERSION;
    u->has_pack = app.gp.present;
    u->pack_id = app.gp.pack.id;
    u->pack_source = app.gp.source;
    u->allow_no_cart = !app.gp.present;  // generic mode only
    u->pack_media = app.gp.present ? gamepack_media_name(app.gp.pack.media) : NULL;
    u->capture_action = UI_CAPTURE_NONE;
    u->startup_window_scale = app.settings.video.window_scale;
    u->screen = UI_SCREEN_SELECT_ROM;
    u->menu_return = UI_SCREEN_SELECT_ROM;
    set_title(NULL);

    // Cartridge to start with: command line (not remembered) > remembered ROM > Select-ROM screen.
    // (The window doesn't exist yet; init_cb applies the title.)
    if (u->blocked[0]) {
        fprintf(stderr, "breadbin-6502: %s\n", u->blocked);
    } else if (app.cli_cart) {
        load_rom(app.cli_cart, LOAD_CLI);
    } else if (app.settings.rom_path[0]) {
        if (platform_file_exists(app.settings.rom_path)) {
            load_rom(app.settings.rom_path, LOAD_REMEMBERED);
        } else {
            set_message(true, "The last ROM wasn't found: %s", app.settings.rom_path);
        }
    }
    if (u->screen == UI_SCREEN_NONE) u->menu_return = UI_SCREEN_NONE;
    if (replay_ready && !start_playback() && app.cli_verify) exit(2);
    if (app.cli_record && u->cart_loaded) start_recording();
    if (app.cli_headless) {
        if (!u->cart_loaded) exit(2);
        for (long i = 0; i < app.quit_after_frames; i++) step_frame();
        stop_recording(NULL);
        coverage_flush();
        recomp_stats();
        exit(0);
    }
    if (app.cli_verify) {
        // headless: every frame of the replay, including disk/tape loading
        while (app.playing) step_frame();
        coverage_flush();
        recomp_stats();
        exit(app.player.diverged ? 1 : 0);
    }

    video_settings_t vs = app.settings.video;
    if (app.scale_override) vs.window_scale = app.scale_override;
    const core_video_t fb = core_video(app.core);
    int w, h;
    video_window_size(&fb, &vs, &w, &h);
    sapp_icon_desc icon = { 0 };
    if (app.icon.rgba) {
        icon.images[0] = (sapp_image_desc){
            .width = app.icon.width,
            .height = app.icon.height,
            .pixels = { app.icon.rgba, (size_t)app.icon.width * (size_t)app.icon.height * 4 },
        };
    }
    return (sapp_desc){
        .init_cb = init_cb,
        .frame_cb = frame_cb,
        .event_cb = event_cb,
        .cleanup_cb = cleanup_cb,
        .width = w,
        .height = h,
        .fullscreen = app.settings.video.fullscreen,
        .window_title = app.title,
        .icon = icon,
        .enable_dragndrop = true,
        .max_dropped_files = 1,
        .enable_clipboard = true,
        .logger.func = slog_func,
    };
}

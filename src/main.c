#define BB_GENERIC_ID "generic"         // settings folder without a game pack
#define BB_ICON_MAX 512
#define BB_BANNER_MAX 2048
#define BB_MAX_FRAMES_PER_TICK 4        // catch-up limit after a hitch
#define BB_MAX_ACCUM_SEC 0.25
#define BB_WARP_BUDGET_MS 14.0          // emulation time per display frame while loading

// Game pack built into the executable (generated by CMake; size 0 = none).
extern const unsigned char bb_gamepack_toml[], bb_gamepack_icon[], bb_gamepack_banner[];
extern const unsigned long bb_gamepack_toml_size, bb_gamepack_icon_size, bb_gamepack_banner_size;

typedef enum {
    LOAD_INTERACTIVE,   // picked by the user: confirm unknown dumps, remember it
    LOAD_REMEMBERED,    // the saved ROM at startup: already accepted once
    LOAD_CLI,           // command line: played, not remembered
    LOAD_CONFIRMED,     // unknown dump, user chose "Play anyway": remember it
} load_mode_t;

static struct {
    core_t* core;
    sysroms_t roms;
    settings_t settings;
    settings_t defaults;                // built-in + game pack defaults
    char settings_path[SETTINGS_PATH_MAX];
    gamepack_loaded_t gp;               // gp.present false = generic mode
    image_t icon, banner;
    char pending_path[SETTINGS_PATH_MAX];   // unknown dump waiting for "Play anyway"
    media_image_t media;                // inserted disk/tape (fmt UNKNOWN = none)
    autostart_t boot;
    bool booting;                       // disk/tape loading at warp speed
    bool browser_swap;                  // the built-in browser was opened for "Swap disk/tape"
    bool settings_dirty;
    bool settings_corrupt;              // keep a backup before the first save
    ui_state_t ui;
    double frame_period;
    double accum;
    long quit_after_frames;             // --frames N (0 = run until closed)
    int scale_override;                 // --scale N (this launch only)
    const char* sysrom_dir;
    const char* cli_cart;
    const char* cli_settings;
    const char* cli_gamepack;
    bool cli_generic;                   // --generic: ignore built-in / bundled packs
    int cli_video_std;                  // --pal / --ntsc: 0 = game pack or PAL, 1 = PAL, 2 = NTSC
    char title[160];
    bool window_ready;
} app;

static void update_title(void) {
    if (app.window_ready) sapp_set_window_title(app.title);
}

// ---- settings --------------------------------------------------------------

static void save_settings(void) {
    if (!app.settings_dirty || !app.settings_path[0]) {
        return;
    }
    if (app.settings_corrupt) {
        char bak[SETTINGS_PATH_MAX + 8];
        snprintf(bak, sizeof(bak), "%s.bad", app.settings_path);
        platform_replace_file(app.settings_path, bak);
        fprintf(stderr, "breadbin-6502: kept the unreadable settings file as %s\n", bak);
        app.settings_corrupt = false;
    }
    char err[512];
    if (settings_save_file(&app.settings, app.settings_path, err, sizeof(err))) {
        app.settings_dirty = false;
    } else {
        fprintf(stderr, "breadbin-6502: %s\n", err);
    }
}

static void load_settings(void) {
    app.settings = app.defaults;
    const char* id = app.gp.present ? app.gp.pack.id : BB_GENERIC_ID;
    if (app.cli_settings) {
        snprintf(app.settings_path, sizeof(app.settings_path), "%s", app.cli_settings);
    } else if (!platform_settings_path(id, app.settings_path, sizeof(app.settings_path))) {
        fprintf(stderr, "breadbin-6502: no config directory; settings won't be saved\n");
        app.settings_path[0] = 0;
        return;
    }
    bool missing = false;
    char err[512], warns[2048];
    if (!settings_load_file(&app.settings, app.settings_path, &missing, err, sizeof(err), warns, sizeof(warns))) {
        if (!missing) {
            fprintf(stderr, "breadbin-6502: settings ignored, %s\n", err);
            app.settings_corrupt = true;
        }
    }
    if (warns[0]) {
        fprintf(stderr, "breadbin-6502: settings warnings:\n%s", warns);
    }
}

// ---- cartridge -------------------------------------------------------------

static void set_message(bool is_error, const char* fmt, const char* arg) {
    snprintf(app.ui.message, sizeof(app.ui.message), fmt, arg);
    app.ui.message_is_error = is_error;
}

static void enter_game(void) {
    app.ui.screen = UI_SCREEN_NONE;
    app.ui.capture_action = UI_CAPTURE_NONE;
    app.accum = 0.0;
    input_release_all();
}

static void set_title(const char* rom_name) {
    if (app.gp.present) snprintf(app.title, sizeof(app.title), "%s", app.gp.pack.title);
    else if (rom_name && rom_name[0]) snprintf(app.title, sizeof(app.title), "Breadbin-6502 - %s", rom_name);
    else snprintf(app.title, sizeof(app.title), "Breadbin-6502");
    update_title();
}

static cart_mode_t pack_cart_mode(gamepack_cart_t t) {
    switch (t) {
        case GAMEPACK_CART_8K: return CART_MODE_8K;
        case GAMEPACK_CART_16K: return CART_MODE_16K;
        case GAMEPACK_CART_ULTIMAX: return CART_MODE_ULTIMAX;
        default: return (cart_mode_t)0;
    }
}

static const char* kind_noun(media_kind_t k) {
    return k == MEDIA_KIND_DISK ? "disk" : k == MEDIA_KIND_TAPE ? "tape" : "cartridge";
}

// The game pack's media kind must match the file's (a disk image can't be a cartridge game).
static bool check_kind(media_kind_t k, char* why, size_t why_size) {
    const gamepack_t* p = &app.gp.pack;
    const media_kind_t want = p->media == GAMEPACK_MEDIA_DISK ? MEDIA_KIND_DISK :
                              p->media == GAMEPACK_MEDIA_TAPE ? MEDIA_KIND_TAPE : MEDIA_KIND_CARTRIDGE;
    if (k == want) return true;
    snprintf(why, why_size, "This is a %s image, but %s is a %s game. It's probably a different game.",
             kind_noun(k), p->title, kind_noun(want));
    return false;
}

static rom_status_t check_hash(const char* sha1, char* why, size_t why_size) {
    const gamepack_t* p = &app.gp.pack;
    if (p->known_sha1_count == 0) return ROM_STATUS_UNVERIFIED;
    if (gamepack_knows_sha1(p, sha1)) return ROM_STATUS_KNOWN;
    snprintf(why, why_size, "This doesn't look like a known copy of %s (SHA-1 %s). "
             "It may be a different version or a bad dump, and mods may not work.", p->title, sha1);
    return ROM_STATUS_UNKNOWN;
}

static rom_status_t check_media(const media_image_t* img, char* why, size_t why_size) {
    why[0] = 0;
    if (!app.gp.present) return ROM_STATUS_GENERIC;
    if (!check_kind(media_format_kind(img->fmt), why, why_size)) return ROM_STATUS_UNKNOWN;
    return check_hash(img->sha1, why, why_size);
}

// Check a cartridge against the game pack; why explains an UNKNOWN result.
static rom_status_t check_cart(const cart_t* c, char* why, size_t why_size) {
    why[0] = 0;
    if (!app.gp.present) return ROM_STATUS_GENERIC;
    if (!check_kind(MEDIA_KIND_CARTRIDGE, why, why_size)) return ROM_STATUS_UNKNOWN;
    const gamepack_t* p = &app.gp.pack;
    const cart_mode_t want = pack_cart_mode(p->cart_type);
    if (want && c->mode != want) {
        snprintf(why, why_size, "This is a %s cartridge, but %s is a %s cartridge. It's probably a different game.",
                 cart_mode_name(c->mode), p->title, cart_mode_name(want));
        return ROM_STATUS_UNKNOWN;
    }
    return check_hash(c->sha1, why, why_size);
}

// Take out any disk/tape (the machine keeps running until the caller resets it).
static void eject_media(void) {
    core_set_file_loader(app.core, NULL, NULL);
    core_remove_tape(app.core);
    media_close(&app.media);
    app.booting = false;
    app.ui.loading = false;
    app.ui.can_swap = false;
}

// Reset the machine and autostart the inserted disk/tape (warp until loaded).
static void boot_media(void) {
    if (app.media.fmt == MEDIA_FMT_TAP) {
        core_insert_tape(app.core, app.media.tap_v1, app.media.tap_v1_size);     // rewind
    }
    core_reset(app.core);
    const gamepack_t* p = &app.gp.pack;
    const autostart_opts_t opts = {
        .file = app.gp.present ? p->load_file : NULL,
        .done_pc = app.gp.present ? p->load_done_pc : -1,
        .done_frames = app.gp.present ? (uint32_t)p->load_done_frames : 0,
    };
    autostart_begin(&app.boot, app.core, app.media.fmt, &opts);
    app.booting = true;
    app.ui.loading = true;
    app.ui.loading_seconds = 0.0f;
}

static void file_base_name(const char* path, char* out, size_t out_size) {
    const char* base = path;
    for (const char* p = path; *p; p++) if (*p == '/' || *p == '\\') base = p + 1;
    // Strip the extension before truncating, or a dot inside the name ("v1.06") would be taken for it.
    const char* dot = strrchr(base, '.');
    const int len = (dot && dot != base) ? (int)(dot - base) : (int)strlen(base);
    snprintf(out, out_size, "%.*s", len, base);
}

static void remember_rom(const char* path) {
    if (strcmp(app.settings.rom_path, path) != 0) {
        snprintf(app.settings.rom_path, sizeof(app.settings.rom_path), "%s", path);
        app.settings_dirty = true;
        save_settings();
    }
}

static void insert_cart(const cart_t* cart, const char* path, rom_status_t status, bool remember) {
    eject_media();
    core_insert_cart(app.core, cart);
    ui_state_t* u = &app.ui;
    u->cart_loaded = true;
    u->media_kind = "Cartridge";
    snprintf(u->rom_path, sizeof(u->rom_path), "%s", path);
    if (cart->name[0]) {
        snprintf(u->rom_name, sizeof(u->rom_name), "%s", cart->name);
    } else {
        // many .crt files have an empty name: use the file name without extension
        file_base_name(path, u->rom_name, sizeof(u->rom_name));
    }
    snprintf(u->rom_sha1, sizeof(u->rom_sha1), "%s", cart->sha1);
    u->rom_mode = cart_mode_name(cart->mode);
    u->rom_status = status;
    u->message[0] = 0;
    fprintf(stderr, "breadbin-6502: cartridge \"%s\" (%s, sha1 %s)\n",
            u->rom_name, cart_mode_name(cart->mode), cart->sha1);
    set_title(u->rom_name);
    if (remember) remember_rom(path);
    enter_game();
}

static void insert_media(media_image_t* img, const char* path, rom_status_t status, bool remember) {
    eject_media();
    if (core_has_cart(app.core)) core_remove_cart(app.core);
    app.media = *img;                   // takes over the image's buffers
    memset(img, 0, sizeof(*img));
    core_set_file_loader(app.core, media_serve, &app.media);
    ui_state_t* u = &app.ui;
    const media_kind_t kind = media_format_kind(app.media.fmt);
    static char mode[48];
    snprintf(mode, sizeof(mode), "%s image (%s)", kind_noun(kind), media_format_name(app.media.fmt));
    u->cart_loaded = true;
    u->media_kind = kind == MEDIA_KIND_TAPE ? "Tape" : "Disk";
    u->can_swap = app.media.fmt != MEDIA_FMT_PRG;
    snprintf(u->rom_path, sizeof(u->rom_path), "%s", path);
    file_base_name(path, u->rom_name, sizeof(u->rom_name));
    snprintf(u->rom_sha1, sizeof(u->rom_sha1), "%s", app.media.sha1);
    u->rom_mode = mode;
    u->rom_status = status;
    u->message[0] = 0;
    fprintf(stderr, "breadbin-6502: %s \"%s\" (sha1 %s)\n", mode, u->rom_name, app.media.sha1);
    set_title(u->rom_name);
    if (remember) remember_rom(path);
    boot_media();
    enter_game();
}

static bool load_cart(const char* path, load_mode_t mode);

// Any supported file: cartridge, disk or tape (detected by content, then extension).
static bool load_rom(const char* path, load_mode_t mode) {
    if (app.ui.blocked[0]) return false;
    uint8_t* data = NULL;
    size_t size = 0;
    char err[256];
    if (!rom_read_file(path, TAP_MAX_SIZE, &data, &size, err, sizeof(err))) {
        set_message(true, "%s", err);
        fprintf(stderr, "breadbin-6502: %s\n", err);
        return false;
    }
    const media_format_t fmt = media_detect(path, data, size);
    if (fmt == MEDIA_FMT_CRT || fmt == MEDIA_FMT_BIN) {
        free(data);
        return load_cart(path, mode);
    }
    if (fmt == MEDIA_FMT_UNKNOWN) {
        free(data);
        set_message(true, "%s isn't a C64 cartridge (.crt .bin), disk (.d64 .prg) or tape (.tap .t64) image.", path);
        return false;
    }
    media_image_t img;
    if (!media_open(&img, fmt, data, size, err, sizeof(err))) {   // frees data on failure
        set_message(true, "%s", err);
        fprintf(stderr, "breadbin-6502: %s: %s\n", path, err);
        return false;
    }
    char why[512];
    const rom_status_t status = check_media(&img, why, sizeof(why));
    if (status == ROM_STATUS_UNKNOWN) {
        fprintf(stderr, "breadbin-6502: warning: %s\n", why);
        if (mode == LOAD_INTERACTIVE) {
            snprintf(app.pending_path, sizeof(app.pending_path), "%s", path);
            snprintf(app.ui.confirm_text, sizeof(app.ui.confirm_text), "%s", why);
            app.ui.confirm_open = true;
            media_close(&img);
            return false;
        }
    }
    insert_media(&img, path, status, mode == LOAD_INTERACTIVE || mode == LOAD_CONFIRMED);
    return true;
}

// "Swap disk/tape": put another image of the same kind in, without a reset.
static void swap_media(const char* path) {
    uint8_t* data = NULL;
    size_t size = 0;
    char err[256];
    if (!rom_read_file(path, TAP_MAX_SIZE, &data, &size, err, sizeof(err))) {
        set_message(true, "%s", err);
        return;
    }
    const media_format_t fmt = media_detect(path, data, size);
    const bool same_kind = fmt != MEDIA_FMT_UNKNOWN && fmt != MEDIA_FMT_CRT && fmt != MEDIA_FMT_BIN &&
                           media_format_kind(fmt) == media_format_kind(app.media.fmt);
    if (!same_kind) {
        free(data);
        set_message(true, "That isn't a %s image.", kind_noun(media_format_kind(app.media.fmt)));
        return;
    }
    media_image_t img;
    if (!media_open(&img, fmt, data, size, err, sizeof(err))) {
        set_message(true, "%s", err);
        return;
    }
    media_close(&app.media);
    app.media = img;
    core_set_file_loader(app.core, media_serve, &app.media);
    if (fmt == MEDIA_FMT_TAP) {
        core_insert_tape(app.core, app.media.tap_v1, app.media.tap_v1_size);
        core_tape_play(app.core);
    } else {
        core_remove_tape(app.core);
    }
    char name[64];
    file_base_name(path, name, sizeof(name));
    set_message(false, "Inserted %s. Close the menu to continue.", name);
    fprintf(stderr, "breadbin-6502: swapped in %s (sha1 %s)\n", path, app.media.sha1);
}

static bool load_cart(const char* path, load_mode_t mode) {
    static cart_t cart;     // ~16 KB, keep off the stack
    char err[256];
    if (app.ui.blocked[0]) return false;
    const uint16_t load_addr = app.gp.present ? app.gp.pack.bin_load_address : 0;
    if (!rom_load_cart(path, load_addr, &cart, err, sizeof(err))) {
        set_message(true, "%s", err);
        fprintf(stderr, "breadbin-6502: %s\n", err);
        return false;
    }
    char why[512];
    const rom_status_t status = check_cart(&cart, why, sizeof(why));
    if (status == ROM_STATUS_UNKNOWN) {
        fprintf(stderr, "breadbin-6502: warning: %s\n", why);
        if (mode == LOAD_INTERACTIVE) {
            snprintf(app.pending_path, sizeof(app.pending_path), "%s", path);
            snprintf(app.ui.confirm_text, sizeof(app.ui.confirm_text), "%s", why);
            app.ui.confirm_open = true;
            return false;
        }
    }
    insert_cart(&cart, path, status, mode == LOAD_INTERACTIVE || mode == LOAD_CONFIRMED);
    return true;
}

static void start_without_cart(void) {
    eject_media();
    core_remove_cart(app.core);
    app.ui.cart_loaded = false;
    app.ui.rom_status = ROM_STATUS_NONE;
    app.ui.rom_path[0] = app.ui.rom_name[0] = app.ui.rom_sha1[0] = 0;
    set_title(NULL);
    enter_game();
}

static void select_rom(bool swap) {
    char dir[SETTINGS_PATH_MAX] = { 0 };
    // start in the folder of the current/last ROM
    const char* last = app.ui.rom_path[0] ? app.ui.rom_path : app.settings.rom_path;
    snprintf(dir, sizeof(dir), "%s", last);
    char* sep = strrchr(dir, platform_path_sep());
    if (sep) *sep = 0; else dir[0] = 0;

    char path[SETTINGS_PATH_MAX], err[256];
    switch (platform_open_rom_dialog(dir, path, sizeof(path), err, sizeof(err))) {
        case FILEDIALOG_OK:
            if (swap) swap_media(path); else load_rom(path, LOAD_INTERACTIVE);
            break;
        case FILEDIALOG_CANCEL:
            break;
        case FILEDIALOG_ERROR:
            if (platform_native_dialog_available()) {
                fprintf(stderr, "breadbin-6502: %s; using the built-in browser\n", err);
            }
            app.browser_swap = swap;
            ui_open_file_browser(dir[0] ? dir : NULL);
            break;
    }
    app.accum = 0.0;    // the dialog blocked the frame loop
}

// ---- UI actions ------------------------------------------------------------

static void handle_ui_actions(void) {
    ui_state_t* u = &app.ui;
    if (u->act_video_changed) {
        video_set_settings(&app.settings.video);
        if (app.settings.video.fullscreen != sapp_is_fullscreen()) sapp_toggle_fullscreen();
        app.settings_dirty = true;
    }
    if (u->act_audio_changed) {
        audio_set_settings(&app.settings.audio);
        app.settings_dirty = true;
    }
    if (u->act_input_changed) {
        input_set_config(&app.settings.input);
        app.settings_dirty = true;
    }
    if (u->act_resume) {
        u->screen = u->menu_return;
        u->capture_action = UI_CAPTURE_NONE;
        if (u->screen == UI_SCREEN_NONE) enter_game();
        save_settings();
    }
    if (u->act_reset) {
        if (app.media.fmt != MEDIA_FMT_UNKNOWN) boot_media(); else core_reset(app.core);
        enter_game();
    }
    if (u->act_no_cart) start_without_cart();
    if (u->act_load_path) {
        if (app.browser_swap) swap_media(u->load_path); else load_rom(u->load_path, LOAD_INTERACTIVE);
        app.browser_swap = false;
    }
    if (u->act_confirm_play) {
        u->confirm_open = false;
        load_rom(app.pending_path, LOAD_CONFIRMED);
    }
    if (u->act_confirm_cancel) {
        u->confirm_open = false;
        u->act_select_rom = true;
    }
    if (u->act_select_rom) select_rom(false);
    if (u->act_swap_media && app.media.fmt != MEDIA_FMT_UNKNOWN) select_rom(true);
    if (u->act_quit) {
        save_settings();
        sapp_request_quit();
    }
    u->act_resume = u->act_reset = u->act_quit = u->act_select_rom = u->act_no_cart = false;
    u->act_video_changed = u->act_audio_changed = u->act_input_changed = u->act_load_path = false;
    u->act_confirm_play = u->act_confirm_cancel = u->act_swap_media = false;
}

// ---- sokol callbacks -------------------------------------------------------

static void init_cb(void) {
    stm_setup();
    video_init();
    video_set_settings(&app.settings.video);
    ui_init();
    if (app.banner.rgba) {
        ui_set_banner(app.banner.rgba, app.banner.width, app.banner.height);
        image_free(&app.banner);
    }
    app.window_ready = true;
    update_title();
}

static void frame_cb(void) {
    // a window manager may toggle fullscreen behind our back
    if (sapp_is_fullscreen() != app.settings.video.fullscreen) {
        app.settings.video.fullscreen = sapp_is_fullscreen();
        app.settings_dirty = true;
    }

    ui_frame(&app.ui);
    handle_ui_actions();

    const bool playing = app.ui.screen == UI_SCREEN_NONE;
    if (playing && app.booting) {
        // Warp: as many frames as fit in the budget, no input, no sound.
        const uint64_t t0 = stm_now();
        do {
            core_run_frame(app.core);
            autostart_frame(&app.boot, app.core);
        } while (autostart_loading(&app.boot) && stm_ms(stm_since(t0)) < BB_WARP_BUDGET_MS);
        app.ui.loading_seconds = (float)((double)app.boot.frames / core_frame_rate(app.core));
        if (!autostart_loading(&app.boot)) {
            app.booting = false;
            app.ui.loading = false;
            app.accum = 0.0;
            input_release_all();
            fprintf(stderr, "breadbin-6502: loaded after %.1f s of emulated time\n", app.ui.loading_seconds);
        }
    } else if (playing) {
        app.accum += sapp_frame_duration();
        if (app.accum > BB_MAX_ACCUM_SEC) app.accum = BB_MAX_ACCUM_SEC;
        int n = 0;
        while (app.accum >= app.frame_period && n < BB_MAX_FRAMES_PER_TICK) {
            input_apply(app.core);
            core_run_frame(app.core);
            app.accum -= app.frame_period;
            n++;
        }
    }
    sapp_show_mouse(!playing);

    // Show the machine while playing or behind the menu; nothing behind the Select-ROM screen.
    const bool show_machine = (playing || app.ui.menu_return == UI_SCREEN_NONE) && !app.booting;
    const core_video_t fb = core_video(app.core);
    video_draw(show_machine && app.ui.screen != UI_SCREEN_SELECT_ROM ? &fb : NULL, !playing);
    ui_flush();
    video_present(ui_draw);

    if (app.quit_after_frames > 0 && (long)sapp_frame_count() >= app.quit_after_frames) {
        sapp_request_quit();
    }
}

static void event_cb(const sapp_event* ev) {
    ui_state_t* u = &app.ui;
    const bool capturing = u->capture_action != UI_CAPTURE_NONE;

    if (ev->type == SAPP_EVENTTYPE_FILES_DROPPED) {
        if (sapp_get_num_dropped_files() > 0) load_rom(sapp_get_dropped_file_path(0), LOAD_INTERACTIVE);
        return;
    }
    if (ev->type == SAPP_EVENTTYPE_KEY_DOWN && !ev->key_repeat && !capturing) {
        if (ev->key_code == SAPP_KEYCODE_F11) {
            sapp_toggle_fullscreen();
            return;
        }
        if ((int)ev->key_code == app.settings.input.menu_key) {
            if (u->screen == UI_SCREEN_NONE) {
                u->menu_return = UI_SCREEN_NONE;
                u->screen = UI_SCREEN_MENU;
                u->message[0] = 0;
                input_release_all();
            } else if (u->screen == UI_SCREEN_MENU) {
                u->act_resume = true;   // handled next frame, like the button
            }
            return;
        }
    }
    if (ui_handle_event(ev, u)) {
        return;
    }
    input_handle_event(ev);
}

static void cleanup_cb(void) {
    save_settings();
    ui_shutdown();
    eject_media();
    core_destroy(app.core);
    audio_shutdown();
    video_shutdown();
    image_free(&app.icon);
    gamepack_loaded_free(&app.gp);
}


static void frame_cb(void) {
    // a window manager may toggle fullscreen behind our back
    if (sapp_is_fullscreen() != app.settings.video.fullscreen) {
        app.settings.video.fullscreen = sapp_is_fullscreen();
        app.settings_dirty = true;
    }

    if (app.ui.screen == UI_SCREEN_MENU && app.prev_screen != UI_SCREEN_MENU) {
        app.ui.states_message[0] = 0;
        refresh_state_slots();      // the game or mods may have changed since
    }
    app.prev_screen = app.ui.screen;
    poll_gamepads();
    app.ui.script_text_count = scriptset_texts(app.scripts, &app.ui.script_texts);
    app.ui.drive_led = app.ui.drive_present && core_drive_led(app.core);
    app.ui.overlay_valid = video_screen_area(&app.ui.overlay_x, &app.ui.overlay_y,
                                             &app.ui.overlay_px, &app.ui.overlay_py);
    ui_frame(&app.ui);
    handle_ui_actions();

    const bool playing = app.ui.screen == UI_SCREEN_NONE;
    if (playing && app.booting) {
        // Warp: as many frames as fit in the budget, no input, no sound.
        const uint64_t t0 = stm_now();
        do {
            step_frame();
        } while (app.booting && stm_ms(stm_since(t0)) < BB_WARP_BUDGET_MS);
    } else if (playing) {
        app.accum += sapp_frame_duration();
        if (app.accum > BB_MAX_ACCUM_SEC) app.accum = BB_MAX_ACCUM_SEC;
        int n = 0;
        while (app.accum >= app.frame_period && n < BB_MAX_FRAMES_PER_TICK) {
            step_frame();
            app.accum -= app.frame_period;
            n++;
        }
    }
    sapp_show_mouse(!playing);

    // Show the machine while playing or behind the menu; nothing behind the Select-ROM screen.
    const bool show_machine = (playing || app.ui.menu_return == UI_SCREEN_NONE) && !app.booting;
    const core_video_t fb = core_video(app.core);
    video_draw(show_machine && app.ui.screen != UI_SCREEN_SELECT_ROM ? &fb : NULL, !playing);
    ui_flush();
    video_present(ui_draw);

    if (app.quit_after_frames > 0 && (long)sapp_frame_count() >= app.quit_after_frames) {
        sapp_request_quit();
    }
}

static void open_menu(void) {
    ui_state_t* u = &app.ui;
    u->menu_return = UI_SCREEN_NONE;
    u->screen = UI_SCREEN_MENU;
    u->message[0] = 0;
    input_release_all();
}

// Gamepads: hot-plug notices, Start/Guide for the menu, menu navigation, joystick.
static void poll_gamepads(void) {
    ui_state_t* u = &app.ui;
    gamepad_poll();
    char text[160];
    if (gamepad_take_event(text, sizeof(text))) {
        fprintf(stderr, "breadbin-6502: %s\n", text);
        snprintf(u->toast, sizeof(u->toast), "%s", text);
        u->toast_frames = 150;
    }
    static uint32_t prev;
    const uint32_t buttons = gamepad_buttons_all();
    const uint32_t pressed = buttons & ~prev;
    prev = buttons;
    const bool taken = ui_gamepad(u, buttons);
    const uint32_t menu_buttons = GAMEPAD_BIT(GAMEPAD_START) | GAMEPAD_BIT(GAMEPAD_GUIDE);
    if (!taken && (pressed & menu_buttons) && u->capture_action == UI_CAPTURE_NONE) {
        if (u->screen == UI_SCREEN_NONE) open_menu();
        else if (u->screen == UI_SCREEN_MENU) u->act_resume = true;
    }
    input_set_gamepad(buttons, u->screen == UI_SCREEN_NONE);
}

static void event_cb(const sapp_event* ev) {
    ui_state_t* u = &app.ui;
    const bool capturing = u->capture_action != UI_CAPTURE_NONE;

    if (ev->type == SAPP_EVENTTYPE_FILES_DROPPED) {
        if (sapp_get_num_dropped_files() > 0) load_rom(sapp_get_dropped_file_path(0), LOAD_INTERACTIVE);
        return;
    }
    if (ev->type == SAPP_EVENTTYPE_KEY_DOWN && !ev->key_repeat && !capturing) {
        if (ev->key_code == SAPP_KEYCODE_F11) {
            sapp_toggle_fullscreen();
            return;
        }
        const int key = (int)ev->key_code;
        if (u->screen == UI_SCREEN_NONE && key && key == app.settings.input.quick_save_key) {
            save_state(0);
            return;
        }
        if (u->screen == UI_SCREEN_NONE && key && key == app.settings.input.quick_load_key) {
            load_state(0);
            return;
        }
        if ((int)ev->key_code == app.settings.input.menu_key) {
            if (u->screen == UI_SCREEN_NONE) {
                open_menu();
            } else if (u->screen == UI_SCREEN_MENU) {
                u->act_resume = true;   // handled next frame, like the button
            }
            return;
        }
    }
    if (ui_handle_event(ev, u)) {
        return;
    }
    input_handle_event(ev);
}

static void cleanup_cb(void) {
    stop_recording(NULL);   // closing the window keeps what was recorded
    replay_free(&app.play);
    save_settings();
    ui_shutdown();
    eject_media();
    scriptset_destroy(app.scripts, app.core);
    pluginset_destroy(app.plugins, app.core);   // plugins stop while the machine still exists
    coverage_flush();
    recomp_stats();
    core_destroy(app.core);
    audio_shutdown();
    gamepad_shutdown();
    video_shutdown();
    image_free(&app.icon);
    gamepack_loaded_free(&app.gp);
    modset_free(&app.mods);
}

